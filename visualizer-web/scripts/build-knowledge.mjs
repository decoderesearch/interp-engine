/**
 * Compiles the repository's documentation into `knowledge/bundle.generated.ts`.
 *
 * The bundle is committed, and that is the point. Vercel builds this directory
 * with its Root Directory set to `visualizer-web`, so reading `../docs` at
 * build time would make the deployment depend on a dashboard toggle that the
 * repository cannot declare. A committed bundle needs nothing outside this
 * directory, and it also solves the inverse problem: `vercel.json`'s
 * `ignoreCommand` skips the build when a commit touched nothing here, so a
 * docs-only commit would never reach the reader. Regenerating in the same
 * commit is what makes the deploy fire.
 *
 * Two invariants the rest of the feature leans on:
 *
 *   - The output is a pure function of the sources and the manifest order.
 *     Nothing here writes a timestamp, a git SHA or a file mtime. The bundle
 *     becomes the head of an Anthropic prompt marked `cache_control`, and one
 *     byte of per-build noise turns every cache read into a cache write at
 *     1.25x -- a cost regression with no symptom other than the bill.
 *   - Missing the whole source tree is tolerated; missing one file is not.
 *     A checkout without `../docs` is a legitimate way to build this directory
 *     and keeps the committed bundle. A checkout that has `docs/` but not
 *     `docs/USAGE.md` is drift, and drift should stop the build.
 *
 * Usage:
 *   node scripts/build-knowledge.mjs           write the bundle
 *   node scripts/build-knowledge.mjs --check   fail if the bundle is stale
 */

import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { readdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { DOCS_LISTED, MANIFEST } from "../knowledge/manifest.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const web = resolve(here, "..");
const repo = resolve(web, "..");
const output = join(web, "knowledge", "bundle.generated.ts");

const check = process.argv.includes("--check");

/**
 * Whether the sources are reachable at all. Both are checked because the
 * failure this guards against is building from a copy of `visualizer-web`
 * alone, in which case neither exists; a tree holding one but not the other is
 * strange enough to be worth the error it will produce a moment later.
 */
function sourcesPresent() {
  return (
    existsSync(join(repo, "docs")) && existsSync(join(repo, "interp_engine"))
  );
}

/** The fence language for a document, so the model reads code as code. */
const FENCE = {
  markdown: "markdown",
  python: "python",
  typescript: "typescript",
};

/**
 * Assert `docs/` holds exactly what the manifest names. Extra files are the
 * interesting direction -- a doc written upstream that nobody remembered to
 * list is precisely the gap that makes the bot confidently out of date -- but
 * a manifest entry pointing at a deleted file is caught here too rather than
 * as a read error further down.
 */
async function checkDocsCoverage() {
  const present = (await readdir(join(repo, "docs")))
    .filter((name) => name.endsWith(".md"))
    .sort();
  const listed = new Set(DOCS_LISTED);

  const unlisted = present.filter((name) => !listed.has(name));
  if (unlisted.length > 0) {
    throw new Error(
      `docs/ holds ${unlisted.join(", ")}, which knowledge/manifest.mjs does not name.\n` +
        `Add an entry (with a 'why' line saying when to reach for it) or delete the file.`,
    );
  }

  const missing = DOCS_LISTED.filter((name) => !present.includes(name));
  if (missing.length > 0) {
    throw new Error(
      `knowledge/manifest.mjs names docs/${missing.join(", docs/")}, which no longer exist.`,
    );
  }
}

/**
 * The generated module: data only. How the documents are framed for the model
 * lives in the hand-written `knowledge/index.ts`, so the wording of the prompt
 * can be edited without regenerating, and regenerating never clobbers wording.
 *
 * One document per line, JSON-encoded. Lines are long, but a diff then names
 * the documents that changed instead of reporting that the single line in the
 * file is different.
 */
function render(documents) {
  const entries = documents
    .map((doc) => `  ${JSON.stringify(doc)},`)
    .join("\n");

  return `// Generated by scripts/build-knowledge.mjs from knowledge/manifest.mjs. Do not edit.
//
// Run \`npm run knowledge\` after changing any source it names; \`npm run knowledge:check\`
// fails when this file has drifted from them. The framing that turns these documents into a
// prompt is in ./index.ts, which is hand-written.

/** One source file, verbatim, with the orientation the manifest gave it. */
export interface KnowledgeDocument {
  /** Repo-root-relative, and what the model is told to cite. */
  path: string;
  title: string;
  /** When to reach for this document. */
  why: string;
  /** Fence language, so source reads as source. */
  kind: string;
  text: string;
}

export const KNOWLEDGE_DOCUMENTS: readonly KnowledgeDocument[] = [
${entries}
];
`;
}

async function main() {
  if (!sourcesPresent()) {
    // Not a failure. See the header: this is what building a checkout of this
    // directory alone looks like, and the committed bundle is already correct.
    console.warn(
      "[knowledge] ../docs and ../interp_engine are not present; keeping the committed bundle.",
    );
    return;
  }

  await checkDocsCoverage();

  const documents = [];
  for (const source of MANIFEST) {
    const absolute = join(repo, source.path);
    if (!existsSync(absolute)) {
      throw new Error(
        `knowledge/manifest.mjs names ${source.path}, which does not exist.`,
      );
    }
    documents.push({
      path: source.path,
      title: source.title,
      why: source.why,
      kind: FENCE[source.kind] ?? "text",
      // Newlines normalized so a checkout with different line endings does not
      // rewrite the cached prefix.
      text: (await readFile(absolute, "utf8")).replace(/\r\n/g, "\n").trimEnd(),
    });
  }

  const rendered = render(documents);
  const bytes = documents.reduce((sum, doc) => sum + doc.text.length, 0);
  // Bytes only. This line used to divide by four and report ~93k tokens; the
  // same string measures 103k on Haiku and 132k on Sonnet, because the
  // tokenizer changed at Claude 4.7. There is no one token count to print
  // here, and a wrong one is worse than none where someone sizes the prefix.
  const summary = `${documents.length} documents, ${(bytes / 1024).toFixed(0)} KB`;

  const existing = existsSync(output) ? await readFile(output, "utf8") : null;
  if (existing === rendered) {
    console.log(`[knowledge] up to date -- ${summary}`);
    return;
  }

  if (check) {
    console.error(
      `[knowledge] knowledge/bundle.generated.ts is stale. Run \`make viz-knowledge\` or \`cd visualizer-web && npm run knowledge\` and commit the result.`,
    );
    process.exitCode = 1;
    return;
  }

  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, rendered, "utf8");
  console.log(`[knowledge] wrote knowledge/bundle.generated.ts -- ${summary}`);
}

main().catch((error) => {
  console.error(`[knowledge] ${error.message}`);
  process.exitCode = 1;
});
